/* Helpers                                                              */
/* ------------------------------------------------------------------ */

function jurisdictionTitle(jur: JurisdictionCode): string {
  switch (jur) {
    case "US-CA":
      return "STATE BAR OF CALIFORNIA";
    case "US-MD":
      return "MARYLAND COURT OF APPEALS (AIS)";
    case "US-IL":
      return "ILLINOIS ARDC ANNUAL REGISTRATION";
    case "US-DC":
      return "D.C. CAPITAL PRO BONO HONOR ROLL";
    case "US-TX":
      return "STATE BAR OF TEXAS";
    default:
      return jur;
  }
}

function barNumberLabel(jur: JurisdictionCode): string {
  switch (jur) {
    case "US-CA":
      return "Cal. Bar #";
    case "US-MD":
      return "MD Attorney #";
    case "US-IL":
      return "ARDC #";
    case "US-DC":
      return "D.C. Bar #";
    case "US-TX":
      return "TX Bar #";
    case "US-NJ":
      return "NJ Bar ID";
    case "US-MA":
      return "BBO #";
    case "US-NY":
      return "NY Bar #";
    case "US-FL":
      return "FL Bar #";
  }
}

function reportingPeriod(jur: JurisdictionCode, year: number): string {
  if (jur === "US-MD") {
    return `July 1, ${year - 1} – June 30, ${year}`;
  }
  if (jur === "US-FL") {
    return `July 1, ${year - 1} – June 30, ${year}`;
  }
  return `January 1 – December 31, ${year}`;
}

/** Download helper. */
export function downloadPortalHandoff(
  jurisdiction: JurisdictionCode,
  summary: BarReportSummary,
  attorney: AttorneyHeader
): void {
  const doc = renderPortalHandoff(jurisdiction, summary, attorney);
  const surname = attorney.name.split(" ").pop()?.toLowerCase().replace(/[^a-z0-9]/g, "-");
  const filename = `${jurisdiction.toLowerCase()}-portal-worksheet-${summary.reportingYear}${
    surname ? `-${surname}` : ""
  }.pdf`;
  doc.save(filename);
}
